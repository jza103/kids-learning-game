// Built-in word lists: three weeks each for grades 3 to 6, with spelling
// words (each with a sentence that uses the word exactly as spelled) and Word
// Match words (each with a kid-friendly meaning that never uses the word).
// A grown-up picks one in the Word lists library and gives it to a kid.
// Within a list, and across the lists of one grade, no two meanings are close
// enough to confuse on the same Word Match board.
const list = (id, grade, week, topic, tip, spelling, vocab) => ({
  id,
  grade,
  week,
  name: `${ordinal(grade)} grade · Week ${week}`,
  topic,
  tip,
  builtIn: true,
  spelling: spelling.map(([word, sentence]) => ({ word, sentence })),
  vocab: vocab.map(([word, definition]) => ({ word, definition })),
});

export function ordinal(n) {
  return `${n}${n === 1 ? 'st' : n === 2 ? 'nd' : n === 3 ? 'rd' : 'th'}`;
}

